// Map any external photo data (e.g. from an API like Picsum) to Indian names and aesthetic titles
export const mapToIndianPhotographer = (item, index) => {
  const nameIndex = Math.abs((Number(item.id) || index) * 7) % INDIAN_NAMES.length
  return {
    ...item,
    author: INDIAN_NAMES[nameIndex],
    location: 'India & Beyond'
  }
}
